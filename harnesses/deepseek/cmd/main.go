// Command kagent-dsh-byo serves a DSH agent through the existing BYO contract.
package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"time"

	a2atype "github.com/a2aproject/a2a-go/v2/a2a"
	"github.com/a2aproject/a2a-go/v2/a2asrv"

	"github.com/kagent-dev/byo-ext/harnesses/deepseek/internal/bridge"
	"github.com/kagent-dev/byo-ext/harnesses/deepseek/internal/config"
	"github.com/kagent-dev/byo-ext/harnesses/deepseek/internal/supervisor"
	"github.com/kagent-dev/kagent/go/adk/pkg/app"
	processconfig "github.com/kagent-dev/kagent/go/core/pkg/config"
	"github.com/kagent-dev/kagent/go/harness/runtime/continuation"
	"github.com/kagent-dev/kagent/go/pkg/logging"
	"github.com/kagent-dev/kagent/go/pkg/telemetry"
)

func main() {
	if len(os.Args) > 1 && os.Args[1] == supervisor.Mode {
		os.Exit(supervisor.Run(os.Args[2:]))
	}
	executable := flag.String("dsh-bin", "dsh", "DSH executable (must match the pinned version)")
	dataDir := flag.String("data-dir", "/data", "absolute durable data directory")
	port := flag.String("port", "80", "private A2A gRPC port")
	check := flag.Bool("check", false, "validate compiled configuration and DSH version, then exit")
	flag.Parse()
	logger, err := logging.New(os.Stderr, "info")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	ctx := logging.IntoContext(context.Background(), logger)
	// These inputs are generated by the controller; this reference binary adds no CRD fields.
	if err := run(ctx, *executable, *dataDir, *port, *check, os.Getenv, os.Environ()); err != nil { //nolint:forbidigo // BYO controller payloads and platform runtime environment.
		logger.ErrorContext(ctx, "dsh byo stopped", "error", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, executable, dataDir, port string, check bool, getenv func(string) string, environment []string) error {
	cfg, err := config.Parse([]byte(getenv("KAGENT_CONFIG_JSON")))
	if err != nil {
		return err
	}
	var card a2atype.AgentCard
	if err := json.Unmarshal([]byte(getenv("KAGENT_AGENT_CARD_JSON")), &card); err != nil {
		return fmt.Errorf("failed to decode BYO agent card: %w", err)
	}
	if card.Name == "" {
		return fmt.Errorf("agent card name is required")
	}
	runner, err := bridge.New(cfg, executable, dataDir, environment)
	if err != nil {
		return err
	}
	validateCtx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	if err := runner.Validate(validateCtx); err != nil {
		return err
	}
	store, err := continuation.New(dataDir+"/adapter", "dsh-byo", bridge.ValidateSessionID)
	if err != nil {
		return err
	}
	if check {
		return nil
	}
	runtimeConfig := cfg.Runtime
	level := runtimeConfig.LogLevel
	if level == "" {
		level = "info"
	}
	logger, err := logging.New(os.Stderr, level)
	if err != nil {
		return err
	}
	ctx = logging.IntoContext(ctx, logger)
	identity := processconfig.RuntimeTelemetry(runtimeConfig.GetTelemetry()).WithEnvironment(environment)
	identity.Provider = "openai"
	identity.Model = cfg.Agent.Model.Model
	// Leave the runtime/name/namespace identity tuple unset: the shared catalog
	// has no DSH runtime and rejects partial identities. Exporter resources still
	// receive the platform's OTEL environment; do not label DSH as Go ADK.
	executor, err := bridge.NewExecutor(runner, store, identity)
	if err != nil {
		return err
	}
	providers, err := telemetry.Init(ctx, telemetry.Options{Config: identity.ExporterConfig(), Identity: identity.ResourceIdentity(), Defaults: identity.ResourceDefaults(card.Name), DeferMetrics: true})
	if err != nil {
		return fmt.Errorf("failed to initialize BYO telemetry: %w", err)
	}
	defer func() {
		shutdownCtx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		if err := providers.Shutdown(shutdownCtx); err != nil {
			logging.FromContext(ctx).ErrorContext(ctx, "failed to shutdown byo telemetry", "error", err)
		}
	}()
	application, err := app.New(app.AppConfig{
		AgentCard: card, Port: port, AppName: card.Name, ControlPlaneURL: runtimeConfig.ControlPlaneUrl,
		MaxContentLength: runtimeConfig.MaxContentLength, Logger: logging.FromContext(ctx), Telemetry: identity, Flush: providers.ForceFlush,
		HandlerOpts: []a2asrv.RequestHandlerOption{a2asrv.WithExecutorContextInterceptor(startMetrics(providers.StartMetrics)), a2asrv.WithCallInterceptors(executor)},
	}, executor)
	if err != nil {
		return fmt.Errorf("failed to construct BYO A2A application: %w", err)
	}
	return application.Run()
}

type startMetrics func()

func (start startMetrics) Intercept(ctx context.Context, _ *a2asrv.ExecutorContext) (context.Context, error) {
	start()
	return ctx, nil
}
